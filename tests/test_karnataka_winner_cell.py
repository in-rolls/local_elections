"""Splitting a 2016 Karnataka winner cell into name, relation and address."""

import pytest

from local_elections.states.karnataka.parse_tzp import _split


@pytest.mark.parametrize(
    ("cell", "name", "relation"),
    [
        ("ಮಮತ ಎಂ.ಶೆಟ್ಟಿ, ಕೋಂ: ಮೋಹನ್ ದಾಸ್ ಶೆಟ್ಟಿ, ದೇವಸ್ಥ ಬಳಿ", "ಮಮತ ಎಂ.ಶೆಟ್ಟಿ", "ಮೋಹನ್ ದಾಸ್ ಶೆಟ್ಟಿ"),
        ("ಎಂ.ಡಿ.ಸುಧಾ ಕೋಂ.ಎಸ್.ದ್ಯಾವೇಗೌಡ", "ಎಂ.ಡಿ.ಸುಧಾ", "ಎಸ್.ದ್ಯಾವೇಗೌಡ"),
        ("ಪೂರ್ಣಿಮಾ ಗೋಪಾಲ್ ಕೋಂ", "ಪೂರ್ಣಿಮಾ ಗೋಪಾಲ್", ""),
        ("ಓಲೇಕಾರ ಚಂದವ್ವ ಸಂಗಪ್ಪ ಸಾ|| ಚಿನ್ನಾಪೂರ", "ಓಲೇಕಾರ ಚಂದವ್ವ ಸಂಗಪ್ಪ", ""),
        ("ಚಾಂಗುನಾಬಾಯಿ ಮೋಹನ ಸಾ| ಪೋಲಕಪಳ್ಳಿ ತಾಂಡಾ", "ಚಾಂಗುನಾಬಾಯಿ ಮೋಹನ", ""),
        ("ಸುರೇಖಾಗೌಡತಿ ಶಂಕರಗೌಡ ಬಿರೆದಾರ ಸಾಃ ಸುಂಬಡ ತಾಃ ಜೇವಗಿ", "ಸುರೇಖಾಗೌಡತಿ ಶಂಕರಗೌಡ ಬಿರೆದಾರ", ""),
        ("ಪಾಲಪ್ಪ, ಎಂ.ಪಿ.ಪ್ರಕಾಶನಗರ ಹಂಪಿ", "ಪಾಲಪ್ಪ", ""),
        ("ಮಲ್ಲಮ್ಮ ಶಿದ್ರಾಮಪ್ಪ ಯತ್ನಟ್ಟಿ", "ಮಲ್ಲಮ್ಮ ಶಿದ್ರಾಮಪ್ಪ ಯತ್ನಟ್ಟಿ", ""),
        ("ಪೂರ್ಣಿಮಾ ಗೋಪಾಲ್ ಕೋಂ, ಗೋಪಾಲ, ಚೌಡ್ಲು ಗ್ರಾಮ", "ಪೂರ್ಣಿಮಾ ಗೋಪಾಲ್", "ಗೋಪಾಲ"),
        ("ಸರಸ್ವತಿ ಸಾ; ಹೂನಿಗೇರಾ ತಾ; ಮತ್ತು ಜಿಲ್ಲೆ;ಯಾದಗಿರಿ", "ಸರಸ್ವತಿ", ""),
        ("ನಾಗನಗೌಡ ಬಸನಗೌಡ ರೋಣದ ಮುಡಿಪೋ:ಗೋನಾಳ ತಾ: ಬದಾಮಿ", "ನಾಗನಗೌಡ ಬಸನಗೌಡ ರೋಣದ", ""),
        ("ಕನಕಪ್ಪ ರಂಗಪ್ಪ ಬಂದಕೇರಿ ಮು/ಪೋ:ಹಿರೇಬೂದಿಹಾಳ", "ಕನಕಪ್ಪ ರಂಗಪ್ಪ ಬಂದಕೇರಿ", ""),
        ("ಸವೀತಾ ಧಮೇಂದ್ರ ಮನೆ ಸಂಖ್ಯೆ 163 ಯರನಳ್ಳಿ", "ಸವೀತಾ ಧಮೇಂದ್ರ", ""),
        ("ಸುನೀತಾ, ಕೋಂ: ರಾಮಪ್ಪ", "ಸುನೀತಾ", "ರಾಮಪ್ಪ"),
        ("ಟಿ.ಜಿ. ನರಸಿಂಹಮೂರ್ತಿ ನಂ.119 ಕರಗದ ಬೀದಿ", "ಟಿ.ಜಿ. ನರಸಿಂಹಮೂರ್ತಿ", ""),
        ("ಜಗದೀಶ ಗಿರಿಯಣ್ಣ ನಾಯಕ ಪೋ:ಮೊಗಟಾ", "ಜಗದೀಶ ಗಿರಿಯಣ್ಣ ನಾಯಕ", ""),
        ("ವಿಲಾಸ ಚಂದ್ರು ನಾಯ್ಕ ಫ್ಲಾಟ್ ನಂ.320 ರಾಮನಗರ", "ವಿಲಾಸ ಚಂದ್ರು ನಾಯ್ಕ", ""),
        ("ಆದೂರು ಎಂ.ಮುನಿರಾಜು ಹಳೇ ನಂ.117", "ಆದೂರು ಎಂ.ಮುನಿರಾಜು", ""),
        ("ಚಂದ್ರಶೇಖರ ಚಿನ್ನಣಗೌಡ ಪೋ|| ಪಾಟೀಲ", "ಚಂದ್ರಶೇಖರ ಚಿನ್ನಣಗೌಡ ಪೋ|| ಪಾಟೀಲ", ""),
    ],
)
def test_the_name_is_split_from_relation_and_address(cell, name, relation):
    got = _split(cell)
    assert got[0] == name
    assert got[1] == relation


def test_the_address_starts_after_the_mark():
    assert _split("ಕನಕಪ್ಪ ರಂಗಪ್ಪ ಬಂದಕೇರಿ ಮು/ಪೋ:ಹಿರೇಬೂದಿಹಾಳ")[2] == "ಹಿರೇಬೂದಿಹಾಳ"


def test_a_house_number_keeps_its_digits():
    assert _split("ಜಯಮಾಲ ನಂ.71 ಕಲ್ಲುಬಾಳು")[2] == "71 ಕಲ್ಲುಬಾಳು"
